public class MainActivity extends AppCompatActivity{
    private EditText phoneNumberEdit;
    String phoneSTR;
    SharedPreferences sp;
    AirplaneModeChangeReceiver airplaneModeChangeReceiver = new AirplaneModeChangeReceiver();

    @Override
    protected void onCreate(Bundle savedInstanceState) {
        super.onCreate(savedInstanceState);
        setContentView(R.layout.activity_main);
        this.setRequestedOrientation(ActivityInfo.SCREEN_ORIENTATION_PORTRAIT); // אי אפשר לשנות את כיוון המסך

        sp = getSharedPreferences("UserPhone", Context.MODE_PRIVATE);
        phoneSTR = "איש קשר או מספר";
        SharedPreferences.Editor editor= sp.edit();
        editor.putString("phoneNumberSave" , phoneSTR).apply();
        Intent H_P = new Intent(this, HomeScreen.class);
        startActivity(H_P);


    }

    @Override
    protected void onStart() {
        super.onStart();
        IntentFilter filter = new IntentFilter(Intent.ACTION_AIRPLANE_MODE_CHANGED);
        registerReceiver(airplaneModeChangeReceiver, filter);
    }

    @Override
    protected void onStop() {
        super.onStop();
        unregisterReceiver(airplaneModeChangeReceiver);
    }


}








